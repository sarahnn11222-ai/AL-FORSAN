function renderRules() {
    const sections = [
        { key: "general", id: "generalRules" },
        { key: "rp", id: "rpRules" },
        { key: "scenario", id: "scenarioRules" },
        { key: "crime", id: "crimeRules" }
    ];

    sections.forEach(section => {
        const container = document.getElementById(section.id);

        if (!container) return;

        container.innerHTML = rulesData[section.key].map((rule, index) => `
            <article class="rule-card">

                <div class="rule-card-top">
                    <h3>${rule.title}</h3>
                    <span class="rule-level">${rule.level}</span>
                </div>

                <p class="rule-description">${rule.description}</p>

                <div class="rule-details">
                    <h4>التفاصيل:</h4>
                    <ul>
                        ${rule.details.map(detail => `<li>${detail}</li>`).join("")}
                    </ul>
                </div>

                <div class="rule-example">
                    <strong>مثال على المخالفة:</strong>
                    <p>${rule.example}</p>
                </div>

            </article>
        `).join("");
    });
}

document.addEventListener("DOMContentLoaded", renderRules);